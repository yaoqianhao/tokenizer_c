#!/usr/bin/env python3
"""Generate src/nfkc_tables.inc from Python's unicodedata (Unicode standard).

Emits three static C arrays + length macros:

  kDecompEntries[] / kDecompPool[] : cp -> NFKD full decomposition
  kCccEntries[]                    : cp -> canonical combining class (>0 only)
  kComposeEntries[]                : (a,b) -> c canonical composition pairs
                                     that NFKC actually recomposes.

Sorted for binary search.  NFKC composition exclusions are honoured by
verifying candidate pairs with unicodedata.normalize('NFC', ...).
"""
import unicodedata
import sys
import os

def nfkd_of(cp):
    out = []
    stack = [cp]
    while stack:
        c = stack.pop()
        d = unicodedata.decomposition(chr(c))
        if not d:
            out.append(c)
            continue
        parts = d.split()
        if parts and parts[0].startswith('<'):
            parts = parts[1:]
        seq = [int(x, 16) for x in parts]
        stack.extend(reversed(seq))
    return out

def main():
    out_path = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', 'src', 'nfkc_tables.inc'))

    decomp = {}   # cp -> [seq]
    ccc = {}      # cp -> int
    comp = {}     # (a,b) -> c

    for cp in range(0x110000):
        if unicodedata.decomposition(chr(cp)):
            seq = nfkd_of(cp)
            if len(seq) == 1 and seq[0] == cp:
                continue
            decomp[cp] = seq
        cc = unicodedata.combining(chr(cp))
        if cc:
            ccc[cp] = cc

    for cp in range(0x110000):
        d = unicodedata.decomposition(chr(cp))
        if not d or d.startswith('<'):
            continue
        parts = d.split()
        if len(parts) != 2:
            continue
        a, b = int(parts[0], 16), int(parts[1], 16)
        if unicodedata.normalize('NFC', chr(a) + chr(b)) == chr(cp):
            comp[(a, b)] = cp

    lines = []
    lines.append('/* Auto-generated by scripts/gen_nfkc_tables.py -- do not edit. */')
    lines.append('#ifndef TOKENIZER_NFKC_TABLES_INC')
    lines.append('#define TOKENIZER_NFKC_TABLES_INC')
    lines.append('')

    # 1) decomp: entries + pool
    entries = []
    pool = []
    for cp in sorted(decomp):
        seq = decomp[cp]
        entries.append((cp, len(seq)))
        pool.extend(seq)
    lines.append('typedef struct { uint32_t cp; uint32_t off; uint32_t len; } nfkc_decomp_entry;')
    lines.append('#define NFKC_DECOMP_N %d' % len(entries))
    lines.append('static const nfkc_decomp_entry kNfkcDecompEntries[NFKC_DECOMP_N] = {')
    off = 0
    for cp, ln in entries:
        lines.append('{0x%05X, %d, %d},' % (cp, off, ln))
        off += ln
    lines.append('};')
    lines.append('#define NFKC_DECOMP_POOL_N %d' % len(pool))
    lines.append('static const uint32_t kNfkcDecompPool[NFKC_DECOMP_POOL_N] = {')
    for i in range(0, len(pool), 12):
        lines.append('    ' + ', '.join('0x%04X' % x for x in pool[i:i+12]) + ',')
    lines.append('};')
    lines.append('')

    # 2) ccc
    lines.append('typedef struct { uint32_t cp; uint8_t ccc; } nfkc_ccc_entry;')
    lines.append('#define NFKC_CCC_N %d' % len(ccc))
    lines.append('static const nfkc_ccc_entry kNfkcCccEntries[NFKC_CCC_N] = {')
    for cp in sorted(ccc):
        lines.append('{0x%05X, %d},' % (cp, ccc[cp]))
    lines.append('};')
    lines.append('')

    # 3) compose
    lines.append('typedef struct { uint32_t a; uint32_t b; uint32_t c; } nfkc_compose_entry;')
    lines.append('#define NFKC_COMPOSE_N %d' % len(comp))
    lines.append('static const nfkc_compose_entry kNfkcComposeEntries[NFKC_COMPOSE_N] = {')
    for (a, b), c in sorted(comp.items()):
        lines.append('{0x%04X, 0x%04X, 0x%04X},' % (a, b, c))
    lines.append('};')
    lines.append('')
    lines.append('#endif /* TOKENIZER_NFKC_TABLES_INC */')

    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')

    print('decomp entries:', len(entries), 'pool elems:', len(pool))
    print('ccc entries:', len(ccc))
    print('compose entries:', len(comp))
    print('wrote', out_path)

if __name__ == '__main__':
    sys.exit(main())
