#!/usr/bin/env python3
"""Generate src/nfc_tables.inc from Python's unicodedata (Unicode standard).

New file (2026-10-14, NFC mode). It emits the *canonical* (non-compatibility)
decomposition table used by src/nfc.c for Unicode NFC:

    kDecompEntries[] / kDecompPool[] : cp -> full canonical decomposition
                                       (compatibility tags like <compat> are
                                       deliberately ignored, so U+FF0C stays
                                       U+FF0C instead of folding to U+002C)

Canonical combining classes and canonical composition pairs are NOT duplicated
here: NFC reuses nfkc_ccc() / nfkc_compose() from nfkc.c, which are already
canonical-only data (the NFKC composition table is validated with
unicodedata.normalize('NFC', ...) in gen_nfkc_tables.py).

The original src/nfkc_tables.inc (NFKD, compatibility) is left untouched, so
the legacy NFKC path keeps behaving exactly as before.
"""
import unicodedata
import sys
import os


def canonical_of(cp):
    """Full canonical decomposition of cp, recursively expanded.

    Returns [cp] unchanged when the code point has no *canonical* mapping
    (empty decomposition or a compatibility-only one such as <compat>/<wide>).
    """
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith('<'):
        return [cp]
    out = []
    for part in d.split():
        out.extend(canonical_of(int(part, 16)))
    return out


def main():
    out_path = os.path.abspath(os.path.join(os.path.dirname(__file__), '..',
                                            'src', 'nfc_tables.inc'))

    decomp = {}
    for cp in range(0x110000):
        seq = canonical_of(cp)
        if len(seq) == 1 and seq[0] == cp:
            continue
        decomp[cp] = seq

    lines = []
    lines.append('/* Auto-generated by scripts/gen_nfc_tables.py -- do not edit. */')
    lines.append('/* Unicode NFC canonical (non-compatibility) decomposition. */')
    lines.append('#ifndef TOKENIZER_NFC_TABLES_INC')
    lines.append('#define TOKENIZER_NFC_TABLES_INC')
    lines.append('')

    entries = []
    pool = []
    for cp in sorted(decomp):
        seq = decomp[cp]
        entries.append((cp, len(seq)))
        pool.extend(seq)
    lines.append('typedef struct { uint32_t cp; uint32_t off; uint32_t len; } nfc_decomp_entry;')
    lines.append('#define NFC_DECOMP_N %d' % len(entries))
    lines.append('static const nfc_decomp_entry kNfcDecompEntries[NFC_DECOMP_N] = {')
    off = 0
    for cp, ln in entries:
        lines.append('{0x%05X, %d, %d},' % (cp, off, ln))
        off += ln
    lines.append('};')
    lines.append('#define NFC_DECOMP_POOL_N %d' % len(pool))
    lines.append('static const uint32_t kNfcDecompPool[NFC_DECOMP_POOL_N] = {')
    for i in range(0, len(pool), 12):
        lines.append('    ' + ', '.join('0x%04X' % x for x in pool[i:i + 12]) + ',')
    lines.append('};')
    lines.append('')
    lines.append('#endif /* TOKENIZER_NFC_TABLES_INC */')

    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')

    print('canonical decomp entries:', len(entries), 'pool elems:', len(pool))
    print('wrote', out_path)


if __name__ == '__main__':
    sys.exit(main())
