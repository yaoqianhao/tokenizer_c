#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""clean_corpus.py —— 训练 / 评测语料去污染（AI 声明行、样板头、控制字符、超短行）

对应 tokenizer_c 优化报告的两个条目：
    * C1（P0，低成本）：19 个 tok_eval 内置探针语料各含 1 行“（内容由AI生成，仅供参考）”
      声明，被 tok_eval 的 corpus_audit 判为污染，且该行会被当作真实样本参与指标计算；
    * D4（P1）：训练/评测前置门禁 —— 污染行数 = 0 才允许开训/开评。

规则（只删行、不改行内内容；默认 dry-run，加 --apply 才落盘）：
    R1 AI 声明行   ：整行（去括号/空白后）命中 AI 声明模式，且长度 <= --max-decl-len
    R2 样板头      ：整行命中样板头模式（“以下内容由…”“本文档由…”“本回答由…”等）
    R3 控制字符    ：含 C0 控制字符（\\t 除外）—— 由 --drop-control 开启（默认开）
    R4 超短行      ：strip 后长度 < --min-len —— 由 --drop-short 开启（默认关）

安全设计：
    * 默认只打印计划（dry-run），不写任何文件；
    * --apply 时先按 --backup-dir 逐文件备份（原始 sha256 记入日志），再原地改写；
    * 每行决策写入 --log（JSONL：file / line_no / action / rule / text），可完整回溯；
    * --report 输出汇总 JSON（各规则命中数、文件前后行数），可直接作为门禁证据。

用法：
    python benchmark/clean_corpus.py --in-dir E:\\tok_eval\\corpus\\builtin
    python benchmark/clean_corpus.py --in-dir <dir> --apply --backup-dir <bk> \\
        --log <log.jsonl> --report <report.json>
    python benchmark/clean_corpus.py --in-dir <dir> --out-dir <clean_dir>
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import os
import re
import shutil
import sys

AI_PATTERNS = [
    re.compile(p, re.IGNORECASE) for p in (
        r"内容由\s*AI\s*生成",
        r"由\s*AI\s*(生成|创作|撰写)",
        r"AI\s*生成(的)?(内容|文本|回答)?",
        r"人工智能生成",
        r"generated by\s*AI",
        r"AI[- ]generated",
        r"仅供参考[，,。.\s]*$",
    )
]
BOILERPLATE_PATTERNS = [
    re.compile(p, re.IGNORECASE) for p in (
        r"^(以下|下面)(内容|文字|文本|数据)?(均)?(由|为)",
        r"^本文(档)?(内容)?(由|为|系)",
        r"^本(回答|结果|输出)(由|为|系)",
        r"^免责声明",
        r"^(This|The)\s+(content|text|document|answer)\s+(is|was)\s+(generated|produced|written)",
    )
]
_CTRL_RE = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")


def _strip_wrap(line: str) -> str:
    """去掉行首尾的括号/引号/空白，便于对“声明”做整行判定。"""
    return line.strip().strip("（）()【】[]《》<>\"'“”‘’ 　\t")


def classify(line: str, min_len: int = 2, max_decl_len: int = 80,
             drop_short: bool = False, drop_control: bool = True) -> tuple:
    """返回 (keep: bool, rule: str|None)。只做整行语义判定，不改动保留行的内容。"""
    raw = line.rstrip("\n").rstrip("\r")
    s = _strip_wrap(raw)
    if not s:
        return True, None                      # 空行保留（由 parse 侧忽略）
    if drop_control and _CTRL_RE.search(raw):
        return False, "R3_control_chars"
    if len(s) <= max_decl_len:
        for p in AI_PATTERNS:
            if p.search(s):
                return False, "R1_ai_declaration"
        for p in BOILERPLATE_PATTERNS:
            if p.search(s):
                return False, "R2_boilerplate"
    if drop_short and len(s) < min_len:
        return False, "R4_too_short"
    return True, None


def _sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fp:
        for chunk in iter(lambda: fp.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def clean_file(path: str, args, log_fp, stats: dict) -> None:
    rel = os.path.relpath(path, args.in_dir)
    lines = io.open(path, encoding="utf-8", errors="replace",
                    newline="").read().split("\n")
    kept, removed = [], []
    for idx, line in enumerate(lines, 1):
        keep, rule = classify(line, min_len=args.min_len, max_decl_len=args.max_decl_len,
                              drop_short=args.drop_short, drop_control=args.drop_control)
        if keep:
            kept.append(line)
        else:
            removed.append((idx, rule, line))
            stats["rules"][rule] = stats["rules"].get(rule, 0) + 1
            if log_fp:
                log_fp.write(json.dumps({"file": rel, "line_no": idx, "action": "drop",
                                         "rule": rule, "text": line}, ensure_ascii=False) + "\n")
            print("  - %s:%d [%s] %s" % (rel, idx, rule, line.strip()[:80]))
    stats["files"].append({"file": rel, "lines_before": len(lines),
                           "lines_removed": len(removed), "lines_after": len(kept),
                           "sha256_before": _sha256(path)})
    if not removed:
        return
    new_text = "\n".join(kept)
    if args.out_dir:
        dst = os.path.join(args.out_dir, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        io.open(dst, "w", encoding="utf-8", newline="").write(new_text)
        print("  ~ 写出清洗后文件 %s" % dst)
        return
    if args.backup_dir:
        bk = os.path.join(args.backup_dir, rel)
        os.makedirs(os.path.dirname(bk), exist_ok=True)
        shutil.copy2(path, bk)
    if args.apply:
        io.open(path, "w", encoding="utf-8", newline="").write(new_text)
        print("  ~ 原地清洗 %s（- %d 行，备份=%s）"
              % (path, len(removed), args.backup_dir or "无"))


def iter_files(in_dir: str, pattern: str) -> list:
    out = []
    for root, _dirs, files in os.walk(in_dir):
        for fn in sorted(files):
            if fn.endswith(tuple(x.strip() for x in pattern.split(","))):
                out.append(os.path.join(root, fn))
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="clean_corpus.py")
    ap.add_argument("--in-dir", required=True)
    ap.add_argument("--glob", default=".txt,.jsonl,.csv", help="按后缀过滤，逗号分隔")
    ap.add_argument("--out-dir", default=None, help="清洗结果另存目录（不在原文件上改）")
    ap.add_argument("--apply", action="store_true", help="原地落盘（默认 dry-run 只打印计划）")
    ap.add_argument("--backup-dir", default=None, help="原地落盘前的备份目录")
    ap.add_argument("--log", default=None, help="逐行决策 JSONL 路径")
    ap.add_argument("--report", default=None, help="汇总 JSON 路径")
    ap.add_argument("--min-len", type=int, default=2)
    ap.add_argument("--max-decl-len", type=int, default=80,
                    help="声明行判定的最大长度（超过则视为正文，不删）")
    ap.add_argument("--drop-short", action="store_true", help="启用 R4 超短行剔除")
    ap.add_argument("--no-drop-control", dest="drop_control", action="store_false",
                    default=True, help="关闭 R3 控制字符剔除")
    args = ap.parse_args(argv)

    files = iter_files(args.in_dir, args.glob)
    if not files:
        print("[FAIL] %s 下未匹配到 %s 文件" % (args.in_dir, args.glob))
        return 1
    if args.apply and args.out_dir:
        print("[FAIL] --apply 与 --out-dir 互斥（--out-dir 不触碰原文件）")
        return 1
    if args.apply and not args.backup_dir:
        print("[WARN] --apply 未指定 --backup-dir：原文件不可回滚，建议先备份")

    print("== clean_corpus == in=%s files=%d apply=%s out=%s"
          % (args.in_dir, len(files), args.apply, args.out_dir or "(原地)"))
    stats = {"in_dir": args.in_dir, "apply": bool(args.apply),
             "out_dir": args.out_dir, "backup_dir": args.backup_dir,
             "rules": {}, "files": [], "files_scanned": len(files)}
    log_fp = io.open(args.log, "w", encoding="utf-8", newline="\n") if args.log else None
    try:
        for p in files:
            clean_file(p, args, log_fp, stats)
    finally:
        if log_fp:
            log_fp.close()
    total_removed = sum(f["lines_removed"] for f in stats["files"])
    stats["lines_before"] = sum(f["lines_before"] for f in stats["files"])
    stats["lines_after"] = sum(f["lines_after"] for f in stats["files"])
    stats["lines_removed"] = total_removed
    stats["files_touched"] = sum(1 for f in stats["files"] if f["lines_removed"])
    print("== 汇总 == files=%d touched=%d lines: %d -> %d（- %d）规则命中=%s"
          % (stats["files_scanned"], stats["files_touched"], stats["lines_before"],
             stats["lines_after"], total_removed,
             json.dumps(stats["rules"], ensure_ascii=False)))
    if not args.apply and not args.out_dir:
        print("== dry-run：未写盘（加 --apply 或 --out-dir 才落盘）==")
    if args.report:
        with io.open(args.report, "w", encoding="utf-8", newline="\n") as fp:
            json.dump(stats, fp, ensure_ascii=False, indent=2)
        print("== report: %s ==" % args.report)
    return 0


if __name__ == "__main__":
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:  # pragma: no cover
        pass
    sys.exit(main())
